.split(whereSeparator: \.isWhitespace).map(String.init)
let weights = ["regular", "fill", "bold"]

func fetch(_ weight: String, _ name: String) throws -> String {
    let file = weight == "regular" ? name : "\(name)-\(weight)"
    let url = URL(string: "https://cdn.jsdelivr.net/npm/@phosphor-icons/core@\(version)/assets/\(weight)/\(file).svg")!
    let data = try Data(contentsOf: url)
    guard var svg = String(data: data, encoding: .utf8), let open = svg.range(of: ">"), let close = svg.range(of: "</svg>", options: .backwards) else {
        throw NSError(domain: "icons", code: 1, userInfo: [NSLocalizedDescriptionKey: "Unreadable \(file)"])
    }
    svg = String(svg[open.upperBound..<close.lowerBound])
    return svg.replacingOccurrences(of: "\n", with: "")
}

var output = """
// Generated by scripts/make-icons.swift from @phosphor-icons/core \(version). Do not edit.
// Phosphor Icons, MIT License, Copyright (c) 2023 Phosphor Icons. See THIRD_PARTY_NOTICES.md.

enum PhosphorData {
    static let version = "\(version)"

"""
for weight in weights {
    var lines: [String] = []
    for name in names {
        do { lines.append("\(name)\t\(try fetch(weight, name))") }
        catch { FileHandle.standardError.write("missing \(weight)/\(name)\n".data(using: .utf8)!) }
    }
    output += "    static let \(weight) = #\"\"\"\n" + lines.joined(separator: "\n") + "\n\"\"\"#\n\n"
}
output += "}\n"
let destination = URL(fileURLWithPath: #filePath).deletingLastPathComponent().deletingLastPathComponent()
    .appendingPathComponent("Sources/DesignSystem/PhosphorData.swift")
try output.write(to: destination, atomically: true, encoding: .utf8)
print("Wrote \(names.count) icons × \(weights.count) weights to \(destination.path)")
